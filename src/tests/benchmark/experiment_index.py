#!/usr/bin/env python3
"""Refresh the experiment index from measured results and explicit dispositions."""
import argparse
import json
from pathlib import Path
import re


def cell(value):
    return str(value).replace('|', '\\|').replace('\n', ' ')


def report_files(root):
    return sorted(path for path in root.rglob('*.md')
                  if path.name not in {'EXPERIMENT_INDEX.md', 'CONTROLLED_RESULTS.md',
                                       'CONTROLLED_PRELIMINARY_RESULTS.md'}
                  and ('RESULT' in path.name or 'EXPERIMENT' in path.name
                       or path.name == 'BATCHED_INSTRUCTION_COUNTS.md'))


def findings(source):
    """Keep source wording and table context; never normalize historical metrics."""
    blocks = re.split(r'\n\s*\n', source)
    selected = []
    heading = ''
    fenced = False
    for block in blocks:
        if '```' in block:
            if block.count('```') % 2:
                fenced = not fenced
            continue
        if fenced:
            continue
        if block.startswith('#'):
            heading = block.splitlines()[0].lstrip('# ')
            continue
        lines = block.splitlines()
        table = len(lines) > 1 and lines[0].startswith('|') and re.search(r'\|\s*:?-', lines[1])
        if table:
            header = lines[0].lower()
            if not re.search(r'throughput|realtime|cpu time|worker cpu|wall|elapsed|speed|seconds|mean', header):
                continue
            # Number source rows without changing their recorded measurements.
            if lines[0].split('|')[1].strip() != '#':
                lines = ['| # ' + lines[0], '| ---: ' + lines[1]] + [
                    f'| {index} ' + line for index, line in enumerate(lines[2:], 1)]
            selected.append((heading, '\n'.join(lines)))
        elif re.search(r'throughput|speedup|faster|slower|regress|CPU time|wall time', block, re.I):
            # Preserve both positive and negative verdicts, including non-numeric ones.
            if re.search(r'\d|no |not |reject|adopt|retain|remov|inconclusive', block, re.I):
                selected.append((heading, block.strip()))
    return selected


def render(root):
    data = json.loads((root / 'CONTROLLED_RESULTS.json').read_text())
    dispositions = json.loads((root / 'EXPERIMENT_STATUS.json').read_text())
    comparisons = data['comparisons']
    names = {row['experiment'] for row in comparisons}
    unknown = set(dispositions['experiments']) - names
    if unknown:
        raise ValueError('Unknown experiment dispositions: ' + ', '.join(sorted(unknown)))
    complete = sum(row['complete'] for row in comparisons)
    lines = ['# Experiment index', '',
             'Generated by `experiment_index.py`. Update `EXPERIMENT_STATUS.json` for adoption',
             'decisions; measurements come from `CONTROLLED_RESULTS.json`. The controlled',
             'summarizer refreshes this index automatically. Run the generator after changing',
             'a historical report, and use `python3 src/tests/benchmark/experiment_index.py --check`',
             'to detect stale output.', '',
             '## Current decisions', '', dispositions['policy'], '',
             'Historical gains are relative to their recorded controls and configurations.',
             'They are not additive or evidence of the same gain on the current runtime.',
             'A positive measurement does not automatically change adoption status.', '',
             '## Controlled comparisons', '',
             f"{complete}/{len(comparisons)} game comparisons complete; "
             f"{data['valid_observations']}/{data['expected_observations']} valid observations; "
             f"{data['invalid_observations']} retained host-invalid observations.", '',
             'CPU and wall columns are throughput changes: positive is faster. Native',
             'instructions are candidate/control changes: negative is less work. Pairs',
             'counts favorable adjacent CPU comparisons, not statistical significance.',
             'Pending rows have no final gain/loss. See [controls and limitations](CONTROLLED_REASSESSMENT.md)',
             'and [all raw measurements](CONTROLLED_RESULTS.json).', '',
             '| # | Experiment / game | CPU | Wall | Native instructions | Faster pairs | Progress | Current disposition | Evidence |',
             '| ---: | --- | ---: | ---: | ---: | ---: | --- | --- | --- |']
    for index, row in enumerate(comparisons, 1):
        status = dispositions['experiments'].get(row['experiment'],
            {'status': 'Reassessment pending' if not row['complete'] else 'No new default adopted'})
        game = 'Snakes' if row['game'] == 'standard' else 'Sky Force'
        if row['complete']:
            values = [f"{row[key]:+.2f}%" for key in ('cpu_throughput_change_percent',
                      'wall_throughput_change_percent', 'native_instruction_change_percent')]
            pairs = f"{row['favorable_pairs']}/{len(row['paired_cpu_throughput_changes_percent'])}"
        else:
            values, pairs = ['Pending'] * 3, '—'
        disposition = status['status']
        if status.get('note'):
            disposition += ': ' + status['note']
        progress = f"{row['valid']}/{row['expected']}; {row['invalid']} invalid"
        lines.append('| ' + ' | '.join(map(cell, [index, row['experiment'] + ' / ' + game,
            *values, pairs, progress, disposition,
            f"[{row['original_report']}]({row['original_report']})"])) + ' |')
    notes = data.get('comparison_notes', [])
    if notes:
        lines += ['', 'Recorded comparison limitations:', '']
        for note in notes:
            lines.append(f"- **{note['experiment']} / {note['game']}**: {note['text']}")
    if data.get('charging_stability_boundary'):
        lines += ['', 'The guard-publication Sky Force comparison spans the recorded charging-policy',
                  'boundary. All valid samples remain included; see the [host limitations](CONTROLLED_REASSESSMENT.md).']
    reports = report_files(root)
    lines += ['', '## Complete report catalogue', '',
              f'{len(reports)} experiment, measurement, correctness and investigation reports are',
              'discovered below. Some are correctness or profiling studies rather than speed',
              'experiments. Each report retains its exact variants, workloads, controls and',
              'evidence. Historical adoption statements describe that report\'s source revision;',
              'the current dispositions above take precedence for the reassessed experiments.', '',
              '| # | Report | Recorded performance findings |',
              '| ---: | --- | --- |']
    extracted = []
    for index, path in enumerate(reports, 1):
        source = path.read_text()
        title = next((line.lstrip('# ') for line in source.splitlines() if line.startswith('# ')), path.stem)
        relative = path.relative_to(root).as_posix()
        parts = findings(source)
        extracted.append((relative, title, parts))
        link = f'[Findings below](#report-{index})' if parts else 'No performance excerpt; see source report'
        lines.append(f'| {index} | [{cell(title)}]({relative}) | {link} |')
    lines += ['', '## Historical findings and gain/loss tables', '',
              'These are source excerpts, not normalized or independently repeated results.',
              'Their headings, signs, units and caveats are preserved. CPU-time reductions,',
              'wall-throughput gains, profiling shares and microbenchmarks must be read in',
              'their original context. Both gains and losses are included. The linked full',
              'report is authoritative; excerpts do not replace its correctness or workload limits.', '']
    for index, (relative, title, parts) in enumerate(extracted, 1):
        if not parts:
            continue
        lines += [f'<a id="report-{index}"></a>', '<details>',
                  f'<summary>{index}. {title.replace("&", "&amp;").replace("<", "&lt;")}</summary>', '',
                  f'[Full report and evidence]({relative})', '']
        previous = None
        for heading, block in parts:
            if heading != previous:
                lines += [f'**{heading}**', '']
                previous = heading
            # Relative links in nested reports must retain their original base.
            base = Path(relative).parent
            if str(base) != '.':
                block = re.sub(r'\]\((?!https?://|/|#)([^)]+)\)',
                               lambda match: '](' + (base / match[1]).as_posix() + ')', block)
            lines += [block, '']
        lines += ['</details>', '']
    return '\n'.join(lines).rstrip() + '\n'


def write_index(root):
    output = root / 'EXPERIMENT_INDEX.md'
    output.write_text(render(root))
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    output = root / 'EXPERIMENT_INDEX.md'
    if args.check:
        if not output.exists() or output.read_text() != render(root):
            raise SystemExit('Experiment index is stale; run experiment_index.py')
        print('Experiment index is current')
    else:
        print(write_index(root))


if __name__ == '__main__':
    main()
